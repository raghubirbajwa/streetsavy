"""Build original neutral placeholders; no photos, remote assets, or product claims."""
import hashlib
import json
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]


def chunk(kind: bytes, data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)


def placeholder(alternate: bool) -> bytes:
    width, height = 600, 800
    pixels = bytearray()
    for y in range(height):
        pixels.append(0)
        for x in range(width):
            shade = 228 if alternate else 238
            if 110 <= x < 490 and 210 <= y < 590:
                shade = 209 if alternate else 218
                if abs((x - 110) - (y - 210)) < 5 or abs((490 - x) - (y - 210)) < 5:
                    shade = 170
            pixels.extend((shade, shade, shade))
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(bytes(pixels), 9)) + chunk(b"IEND", b"")


metadata = {}
destination = ROOT / "public/fixtures/catalog"
destination.mkdir(parents=True, exist_ok=True)
for view in ("front", "alternate"):
    image = placeholder(view == "alternate")
    metadata[view] = {"sizeBytes": len(image), "sha256": hashlib.sha256(image).hexdigest()}
    for product in range(1, 17):
        if product == 15 and view == "alternate":
            continue
        (destination / f"p{product:02d}-{view}.png").write_bytes(image)

(ROOT / "src/data/fixtures/image-metadata.ts").write_text(
    "// Generated by scripts/build-fixture-placeholders.py; no remote or licensed imagery.\n"
    + "export const fixtureImageMetadata = " + json.dumps(metadata, indent=2) + " as const;\n"
)
