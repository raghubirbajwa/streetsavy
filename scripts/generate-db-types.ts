export type SchemaDatabase = {
  query<T>(sql: string): Promise<{ rows: T[] }>;
};

/** Generate Supabase-compatible column/RPC types from the migrated PostgreSQL catalog. */
export async function databaseTypes(client: SchemaDatabase): Promise<string> {
  const columns = await client.query<{ table_name: string; column_name: string; udt_name: string; is_nullable: string; column_default: string | null }>(
    "select table_name,column_name,udt_name,is_nullable,column_default from information_schema.columns where table_schema='public' order by table_name,ordinal_position",
  );
  const tables = [...new Set(columns.rows.map((row) => row.table_name))];
  const pgType = (type: string): string => {
    if (type.startsWith("_")) return `(${pgType(type.slice(1))})[]`;
    if (["int2", "int4", "int8", "numeric", "float4", "float8"].includes(type)) return "number";
    if (type === "bool") return "boolean";
    if (["json", "jsonb"].includes(type)) return "Json";
    if (type === "void") return "undefined";
    return "string";
  };
  const functions = await client.query<{ name: string; argnames: string[] | null; argtypes: string[]; defaults: number; return_type: string; setof: boolean }>(`
    select p.proname name,p.proargnames argnames,
      array(select typname from unnest(p.proargtypes) with ordinality a(oid,n) join pg_type t on t.oid=a.oid order by n) argtypes,
      p.pronargdefaults defaults,t.typname return_type,p.proretset setof
    from pg_proc p join pg_namespace n on n.oid=p.pronamespace join pg_type t on t.oid=p.prorettype
    where n.nspname='public' and p.prokind='f' and t.typname <> 'trigger' order by p.proname
  `);
  let output = "// GENERATED by npm run types:db from a clean migrated PostgreSQL database. Do not edit.\n";
  output += "export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\nexport type Database = { public: { Tables: {\n";
  for (const table of tables) {
    const fields = columns.rows.filter((row) => row.table_name === table);
    output += `  ${JSON.stringify(table)}: {\n`;
    for (const mode of ["Row", "Insert", "Update"] as const) {
      output += `    ${mode}: {\n`;
      for (const field of fields) {
        const nullable = field.is_nullable === "YES";
        const optional = mode === "Update" || (mode === "Insert" && (nullable || field.column_default !== null));
        output += `      ${JSON.stringify(field.column_name)}${optional ? "?" : ""}: ${pgType(field.udt_name)}${nullable ? " | null" : ""};\n`;
      }
      output += "    };\n";
    }
    output += "    Relationships: [];\n  };\n";
  }
  output += "}; Views: Record<string, never>; Functions: {\n";
  for (const fn of functions.rows) {
    output += `  ${JSON.stringify(fn.name)}: { Args: {`;
    fn.argtypes.forEach((type, index) => {
      output += ` ${JSON.stringify(fn.argnames?.[index] ?? `arg${index}`)}${index >= fn.argtypes.length - fn.defaults ? "?" : ""}: ${pgType(type)};`;
    });
    const result = tables.includes(fn.return_type) ? `Database["public"]["Tables"][${JSON.stringify(fn.return_type)}]["Row"]` : pgType(fn.return_type);
    output += ` }; Returns: ${result}${fn.setof ? "[]" : ""} };\n`;
  }
  return output + "}; Enums: Record<string, never>; CompositeTypes: Record<string, never>; } };\n";
}
